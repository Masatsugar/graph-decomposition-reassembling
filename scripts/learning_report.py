def _number(value):
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    return float(value) if math.isfinite(value) else None


def _mean(values):
    values = [value for raw in values if (value := _number(raw)) is not None]
    return sum(values) / len(values) if values else None


def _sum_complete(points, key):
    values = [point.get(key) for point in points]
    return sum(values) if values and all(v is not None for v in values) else None


def _ratio(numerator, denominator):
    if numerator is None or denominator is None or denominator <= 0:
        return None
    return numerator / denominator


def _source(path):
    if not path.is_file():
        return None
    stat = path.stat()
    result = {
        "path": str(path.resolve()),
        "bytes": stat.st_size,
        "mtime_ns": stat.st_mtime_ns,
    }
    return result


def _read_json(path, issues, *, live=False, capture=None):
    if not path.is_file():
        return None
    data = path.read_bytes()
    if capture is not None:
        capture.update(_source(path))
        capture["bytes"] = len(data)
        capture["sha256"] = hashlib.sha256(data).hexdigest()
    try:
        return json.loads(data)
    except (json.JSONDecodeError, UnicodeDecodeError) as error:
        if not live:
            raise ValueError(f"Invalid JSON: {path}: {error}") from error
        issues.append(f"Snapshot skipped a JSON file being written: {path}")
        return None


def read_auxiliary_losses(path, issues, *, live=False):
    """Stream a fixed-size log snapshot; retain only per-iteration model metrics."""
    if not path.is_file():
        return {}, None
    source = _source(path)
    remaining = source["bytes"]
    losses = {}
    with path.open("rb") as stream:
        line_number = 0
        while remaining:
            line = stream.readline(remaining)
            if not line:
                break
            remaining -= len(line)
            line_number += 1
            try:
                result = json.loads(line)
            except (json.JSONDecodeError, UnicodeDecodeError) as error:
                if live and not remaining and not line.endswith(b"\n"):
                    issues.append(
                        f"Snapshot ignored incomplete trailing log line: {path}"
                    )
                    break
                raise ValueError(f"Invalid log JSON: {path}:{line_number}") from error
            iteration = result.get("training_iteration")
            if type(iteration) is not int or iteration <= 0:
                continue
            model = (
                result.get("info", {})
                .get("learner", {})
                .get("default_policy", {})
                .get("model", {})
            )
            if "candidate_value_loss" in model:
                if iteration in losses:
                    raise ValueError(
                        f"Duplicate model metric iteration {iteration}: {path}"
                    )
                losses[iteration] = _number(model["candidate_value_loss"])
    return losses, source


def summarize_window(points):
    """Preserve unknown counts; zero completed episodes has undefined mean QED."""
    seconds = _sum_complete(points, "seconds")
    counts = {
        key: _sum_complete(points, key)
        for key in (
            "updates",
            "valid_molecules",
            "episodes",
            "quality_sum",
            "sampled_steps",
            "score_requests",
            "score_computations",
            "score_cache_hits",
        )
    }
    peaks = [
        point["gpu_peak_mib"] for point in points if point["gpu_peak_mib"] is not None
    ]
    metrics = {
        key: {
            "mean": _mean(point[key] for point in points),
            "observed_iterations": sum(point[key] is not None for point in points),
        }
        for key in (
            *LEARNER_METRICS,
            "candidate_value_loss",
            "sample_time_ms",
            "learn_time_ms",
        )
    }
    return {
        "iterations": len(points),
        "first_iteration": points[0]["iteration"] if points else None,
        "last_iteration": points[-1]["iteration"] if points else None,
        "seconds": seconds,
        **counts,
        "mean_final_training_qed": _ratio(counts["quality_sum"], counts["episodes"]),
        "molecule_updates_per_second": _ratio(counts["updates"], seconds),
        "valid_molecules_per_second": _ratio(counts["valid_molecules"], seconds),
        "completed_molecules_per_second": _ratio(counts["episodes"], seconds),
        "sampled_steps_per_second": _ratio(counts["sampled_steps"], seconds),
        "gpu_peak_mib": max(peaks) if peaks else None,
        "gpu_peak_observed_iterations": len(peaks),
        "metrics": metrics,
    }


def _curve_point(record, auxiliary):
    chemistry, learner, timers = (
        record.get("chemistry", {}),
        record.get("learner_stats", {}),
        record.get("timers", {}),
    )
    point = {key: _number(record.get(key)) for key in ("seconds", "sampled_steps")}
    point.update(
        {
            key: _number(chemistry.get(key))
            for key in (
                "updates",
                "valid_molecules",
                "episodes",
                "quality_sum",
            )
        }
    )
    point.update(
        {
            "score_requests": _number(chemistry.get("requests")),
            "score_computations": _number(chemistry.get("computations")),
            "score_cache_hits": _number(chemistry.get("hits")),
        }
    )
    point.update({key: _number(learner.get(key)) for key in LEARNER_METRICS})
    point.update(
        {key: _number(timers.get(key)) for key in ("sample_time_ms", "learn_time_ms")}
    )
    point.update(
        {
            "iteration": record["iteration"],
            "candidate_value_loss": auxiliary.get(record["iteration"]),
            "gpu_peak_mib": _number(record.get("peak_gpu_memory_mib")),
            "mean_final_training_qed": _ratio(point["quality_sum"], point["episodes"]),
            "molecule_updates_per_second": _ratio(point["updates"], point["seconds"]),
            "sampled_steps_per_second": _ratio(
                point["sampled_steps"], point["seconds"]
            ),
        }
    )
    return point


def read_training_run(job, sweep_directory, expected_iterations):
    run = Path(job.get("directory", sweep_directory / job["name"]))
    if not run.is_absolute():
        run = sweep_directory / run
    run = run.resolve()
    live = job.get("status") != "complete"
    issues = []
    measurements = run / "measurements.json"
    measurement_source = {}
    records = _read_json(measurements, issues, live=live, capture=measurement_source)
    if records is None:
        records = []
    if not isinstance(records, list):
        raise TypeError(f"Measurements must be an array: {measurements}")
    iterations = [record.get("iteration") for record in records]
    if any(type(value) is not int or value <= 0 for value in iterations):
        raise ValueError(f"Invalid iteration number: {measurements}")
    if len(set(iterations)) != len(iterations):
        raise ValueError(f"Duplicate training iteration: {measurements}")
    records.sort(key=lambda record: record["iteration"])
    iterations = sorted(iterations)
    contiguous = iterations == list(range(1, len(iterations) + 1))
    exact = iterations == list(range(1, expected_iterations + 1))
    if not live and not exact:
        raise ValueError(
            f"Complete run {job['name']} must contain exactly iterations 1.."
            f"{expected_iterations}; observed {len(iterations)}"
        )
    if not contiguous:
        issues.append("Observed iterations contain gaps; snapshot is incomplete")
    if any(record.get("measured") is False for record in records):
        raise ValueError(
            "Learning report expects training iterations, not profiling warmup records"
        )
    auxiliary, log_source = read_auxiliary_losses(
        run / "logs" / "result.json", issues, live=live
    )
    points = [_curve_point(record, auxiliary) for record in records]
    elapsed = 0.0
    for point in points:
        elapsed = (
            elapsed + point["seconds"]
            if elapsed is not None and point["seconds"] is not None
            else None
        )
        point["elapsed_training_seconds"] = elapsed
    summary = _read_json(run / "summary.json", issues, live=live)
    if summary is not None and summary.get("iterations") != len(points):
        if not live:
            raise ValueError(f"Summary and measurement iteration counts differ: {run}")
        issues.append("Summary and snapshot measurement counts differ")
    manifest = _read_json(run / "manifest.json", issues, live=live)
    seed_match = re.search(r"_seed(\d+)(?:_|$)", job["name"])
    seed = int(seed_match[1]) if seed_match else None
    if manifest is not None:
        seed = manifest.get("seed", seed)
    last = points[-50:]
    return {
        "name": job["name"],
        "configuration": re.sub(r"_seed\d+(?:_workers\d+)?$", "", job["name"]),
        "training_seed": seed,
        "training_seed_n": 1 if points else 0,
        "training_seed_sample_sd": None,
        "source_status": job.get("status", "unknown"),
        "state": "complete" if not live and exact else "snapshot",
        "directory": str(run),
        "observed_iterations": len(points),
        "expected_iterations": expected_iterations,
        "contiguous_from_one": contiguous,
        "windows": {
            "whole": summarize_window(points),
            "steady_after_first_three": summarize_window(
                [point for point in points if point["iteration"] > 3]
            ),
            "last_fifty": {
                **summarize_window(last),
                "requested_window": 50,
                "full_window": len(last) == 50,
            },
        },
        "curve": points,
        "issues": issues,
        "sources": {
            "measurements": measurement_source or None,
            "full_log": log_source,
            "manifest": manifest,
            "summary": summary,
            "config_diff": job.get("diff", {}),
        },
    }


def read_evaluations(directory):
    """Read aggregate evaluation files only, without loading molecule/asset arrays."""
    if directory is None:
        return {
            "directory": None,
            "state": "not_provided",
            "datasets": [],
            "runs": [],
            "issues": [],
        }
    directory = Path(directory).resolve()
    if not directory.is_dir():
        raise ValueError(f"Evaluation directory does not exist: {directory}")
    rows, datasets, issues = [], [], []
    for current, subdirectories, files in os.walk(directory):
        subdirectories[:] = sorted(
            name
            for name in subdirectories
            if name
            not in {
                "assets",
                "logs",
                "runs",
                "checkpoints",
                ".git",
                "__pycache__",
            }
        )
        if not {"runs.json", "comparison.json", "evaluation_plan.json"}.intersection(
            files
        ):
            continue
        root = Path(current)
        plan = _read_json(root / "evaluation_plan.json", issues, live=True) or {}
        comparison = _read_json(root / "comparison.json", issues, live=True) or {}
        metadata = {**comparison, **plan}
        raw_rows = _read_json(root / "runs.json", issues, live=True)
        if raw_rows is None:
            raw_rows = comparison.get("runs", [])
        if not isinstance(raw_rows, list):
            raise TypeError(f"Evaluation runs must be an array: {root}")
        datasets.append(
            {
                "directory": str(root),
                "completed_checkpoints": len(raw_rows),
                "planned_checkpoints": metadata.get("total_checkpoints"),
                "checkpoint_iteration": metadata.get("checkpoint_iteration"),
                "explore": metadata.get("explore"),
                "episodes_per_checkpoint": metadata.get("episodes_per_checkpoint"),
                "evaluation_seeds": metadata.get("evaluation_seeds"),
                "source_sweep_directory": metadata.get("sweep_directory"),
            }
        )
        for raw in raw_rows:
            iteration = raw.get(
                "checkpoint_iteration", metadata.get("checkpoint_iteration")
            )
            if iteration is None:
                match = re.search(
                    r"(?:^|[/\\])iteration_(\d+)(?:$|[/\\])", raw.get("checkpoint", "")
                )
                iteration = int(match[1]) if match else None
            rows.append(
                {
                    **raw,
                    "checkpoint_iteration": iteration,
                    "explore": raw.get("explore", metadata.get("explore")),
                    "mean_score": _number(raw.get("mean_score")),
                    "evaluation_directory": str(root),
                    "source_sweep_directory": metadata.get("sweep_directory"),
                }
            )
    complete = bool(datasets) and all(
        item["planned_checkpoints"] is not None
        and item["completed_checkpoints"] == item["planned_checkpoints"]
        for item in datasets
    )
    return {
        "directory": str(directory),
        "state": "complete" if complete else "snapshot",
        "datasets": datasets,
        "runs": rows,
        "issues": issues,
    }


def _rolling_qed(points, width=10):
    return [
        summarize_window(points[max(0, index - width + 1) : index + 1])[
            "mean_final_training_qed"
        ]
        for index in range(len(points))
    ]


def _plots(report, directory):
    """Scientific figures: observed values only, with gaps for missing metrics."""
    os.environ.setdefault("MPLCONFIGDIR", "/tmp/moldr_learning_matplotlib")
    import matplotlib

    matplotlib.use("Agg")
    from matplotlib import pyplot as plt

    outputs = []
    colors = plt.get_cmap("tab10")
    run_colors = {
        run["name"]: colors(index % 10)
        for index, run in enumerate(report["runs"])
    }

    def curve(axis, run, key, color, *, values=None, linestyle="-"):
        points = run["curve"]
        values = [point.get(key) for point in points] if values is None else values
        if not any(value is not None for value in values):
            return
        axis.plot(
            [point["iteration"] for point in points],
            [value if value is not None else float("nan") for value in values],
            label=run["name"],
            color=color,
            linewidth=1.1,
            linestyle=linestyle,
        )

    def save(figure, axes, stem):
        for axis in axes.flat:
            axis.set_xlabel("Training iteration")
            axis.grid(alpha=0.2)
            if axis.lines:
                axis.legend(fontsize=6)
            else:
                axis.text(
                    0.5,
                    0.5,
                    "No observed values",
                    ha="center",
                    transform=axis.transAxes,
                )
        figure.tight_layout()
        for suffix in ("png", "svg"):
            figure.savefig(directory / f"{stem}.{suffix}", dpi=150)
        plt.close(figure)
        outputs.append(stem)

    figure, axes = plt.subplots(2, 2, figsize=(13, 8))
    for index, run in enumerate(report["runs"]):
        color = colors(index % 10)
        curve(
            axes[0, 0],
            run,
            "mean_final_training_qed",
            color,
            values=_rolling_qed(run["curve"]),
        )
        curve(axes[0, 1], run, "entropy", color)
        curve(axes[1, 0], run, "total_loss", color)
        curve(axes[1, 1], run, "molecule_updates_per_second", color)
    for axis, title in zip(
        axes.flat,
        (
            "Training final QED (10-iteration episode-weighted window)",
            "Pooled action entropy",
            "PPO total loss (excludes custom auxiliary loss)",
            "Valid selected molecular updates / second",
        ),
        strict=True,
    ):
        axis.set_title(title, fontsize=10)
    figure.suptitle(
        f"Learning curves: {report['state']}; one training seed per run, no seed SD"
    )
    save(figure, axes, "learning_curves")

    figure, axes = plt.subplots(2, 3, figsize=(15, 8))
    for index, run in enumerate(report["runs"]):
        for axis, key in zip(
            axes.flat,
            (
                "kl",
                "vf_explained_var",
                "candidate_value_loss",
                "policy_loss",
                "vf_loss",
                "sample_time_ms",
            ),
            strict=True,
        ):
            curve(axis, run, key, colors(index % 10))
        # Both smoothed timer components share the final panel; dashed is learn.
        curve(axes[1, 2], run, "learn_time_ms", colors(index % 10), linestyle="--")
    for axis, title in zip(
        axes.flat,
        (
            "KL",
            "Value-function explained variance",
            "Scaled candidate-value Huber loss",
            "Policy loss",
            "Value-function loss",
            "Smoothed timers, ms (sample solid / learn dashed)",
        ),
        strict=True,
    ):
        axis.set_title(title, fontsize=10)
    save(figure, axes, "optimization_diagnostics")

    evaluation_rows = report["evaluation"]["runs"]
    if evaluation_rows:
        figure, axes = plt.subplots(1, 2, figsize=(13, 5), squeeze=False)
        identities = sorted(
            {
                (row.get("configuration", row["name"]), row.get("training_seed"))
                for row in evaluation_rows
            },
            key=str,
        )
        for index, (configuration, seed) in enumerate(identities):
            for axis, explore in zip(axes.flat, (True, False), strict=True):
                points = sorted(
                    (
                        row
                        for row in evaluation_rows
                        if row.get("configuration", row["name"]) == configuration
                        and row.get("training_seed") == seed
                        and row.get("explore") is explore
                        and row["checkpoint_iteration"] is not None
                        and row["mean_score"] is not None
                    ),
                    key=lambda row: row["checkpoint_iteration"],
                )
                if points:
                    # Points avoid implying evaluation at missing iterations or equal budgets.
                    axis.plot(
                        [row["checkpoint_iteration"] for row in points],
                        [row["mean_score"] for row in points],
                        marker="o",
                        linestyle="none",
                        color=run_colors.get(points[0]["name"], colors(index % 10)),
                        label=f"{configuration}, seed {seed}",
                    )
        for axis, explore in zip(axes.flat, (True, False), strict=True):
            budgets = {}
            for row in evaluation_rows:
                iteration = row.get("checkpoint_iteration")
                if row.get("explore") is explore and iteration is not None:
                    budgets.setdefault(iteration, set()).add(
                        str(row.get("episodes", "?"))
                    )
            positions = sorted(budgets)
            axis.set_xticks(
                positions,
                [f"{iteration}\nn={'/'.join(sorted(budgets[iteration]))}"
                 for iteration in positions],
                fontsize=8,
            )
        axes[0, 0].set_title("Checkpoint stochastic evaluation:\nmean final QED")
        axes[0, 1].set_title("Checkpoint greedy evaluation:\nmean final QED")
        figure.suptitle(
            "Independent saved-checkpoint evaluation; absent evaluations omitted"
        )
        save(figure, axes, "checkpoint_evaluations")
    return outputs


def _display(value, digits=3):
    value = _number(value)
    return "—" if value is None else f"{value:.{digits}f}"


