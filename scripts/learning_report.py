def build_report(
    sweep_directory,
    output,
    *,
    evaluation_directory=None,
    require_complete=False,
    expected_iterations=500,
):
    if type(expected_iterations) is not int or expected_iterations <= 0:
        raise ValueError("Expected iterations must be a positive integer")
    sweep_directory = Path(sweep_directory).resolve()
    output = Path(output).resolve()
    issues = []
    sweep = _read_json(sweep_directory / "sweep.json", issues)
    if not sweep or not sweep.get("jobs"):
        raise ValueError("A nonempty sweep.json is required")
    runs = [
        read_training_run(job, sweep_directory, expected_iterations)
        for job in sweep["jobs"]
    ]
    complete = all(run["state"] == "complete" for run in runs)
    if require_complete and not complete:
        missing = ", ".join(
            f"{run['name']} ({run['observed_iterations']}/{expected_iterations})"
            for run in runs
            if run["state"] != "complete"
        )
        raise ValueError(f"Complete training sweep required: {missing}")
    report = {
        "schema_version": 1,
        "captured_at_utc": datetime.now(timezone.utc).isoformat(),
        "state": "complete" if complete else "snapshot",
        "sweep_directory": str(sweep_directory),
        "expected_iterations": expected_iterations,
        "completed_runs": sum(run["state"] == "complete" for run in runs),
        "planned_runs": len(runs),
        "notes": NOTES,
        "runs": runs,
        "evaluation": read_evaluations(evaluation_directory),
    }
    output.mkdir(parents=True, exist_ok=True)
    plots = _plots(report, output)
    report["plots"] = plots
    (output / "learning_report.json").write_text(
        json.dumps(report, indent=2, allow_nan=False) + "\n"
    )
    destination = output / "index.html"
    destination.write_text(_html(report, plots))
    return destination


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sweep-directory", required=True, type=Path)
    parser.add_argument(
        "--evaluation-directory",
        type=Path,
        help="Optional directory containing checkpoint-evaluation iteration/mode roots",
    )
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument(
        "--require-complete",
        action="store_true",
        help="Reject running/planned jobs or any run without all expected iterations",
    )
    parser.add_argument("--expected-iterations", type=int, default=500)
    arguments = parser.parse_args(argv)
    try:
        output = build_report(
            arguments.sweep_directory,
            arguments.output,
            evaluation_directory=arguments.evaluation_directory,
            require_complete=arguments.require_complete,
            expected_iterations=arguments.expected_iterations,
        )
    except (ValueError, TypeError) as error:
        parser.error(str(error))
    print(json.dumps({"report": str(output)}))


if __name__ == "__main__":
    main()
